#!/usr/bin/env python3
"""Render the RQS-2030 standard from rqs-2030.yaml.

usage: build.py           write rqs-2030.json (tools, agents) and RQS-2030.md (people)
       build.py --check   validate the YAML and fail if the generated files are stale

Needs PyYAML for this step only; everything that consumes the standard reads the JSON.
"""
import hashlib
import json
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "rqs-2030.yaml")
OUT_JSON = os.path.join(HERE, "rqs-2030.json")
OUT_MD = os.path.join(HERE, "RQS-2030.md")
CRITERION_FIELDS = ["id", "title", "question", "why", "fail", "meets", "horizon", "evidence", "probes", "refs"]
CRITERION_OPTIONAL = {"core", "red_line", "applies_if"}


def validate(d):
    errs = []

    def walk(x, path):
        if x is None:
            errs.append(f"null value at {path} (an unquoted ', ' inside a flow mapping?)")
        elif isinstance(x, dict):
            for k, v in x.items():
                walk(v, f"{path}/{k}")
        elif isinstance(x, list):
            for i, v in enumerate(x):
                walk(v, f"{path}[{i}]")

    walk(d, "")
    dims = [x["id"] for x in d["dimensions"]]
    refs = {r["id"] for r in d["references"]}
    flags = set(d["applicability_flags"])
    seen = set()
    for dim in d["dimensions"]:
        for c in dim["criteria"]:
            cid = c.get("id", "?")
            if cid in seen:
                errs.append(f"duplicate criterion id {cid}")
            seen.add(cid)
            if not cid.startswith(dim["id"] + "-"):
                errs.append(f"{cid} is filed under {dim['id']}")
            errs += [f"{cid} lacks {k}" for k in CRITERION_FIELDS if k not in c]
            errs += [f"{cid} has unknown key {k}" for k in c if k not in CRITERION_FIELDS and k not in CRITERION_OPTIONAL]
            errs += [f"{cid} cites unknown reference {r}" for r in c.get("refs", []) if r not in refs]
            if c.get("applies_if") and c["applies_if"] not in flags:
                errs.append(f"{cid} applies_if unknown flag {c['applies_if']}")
    for name, prof in d["profiles"].items():
        if set(prof["weights"]) != set(dims):
            errs.append(f"profile {name} weights {sorted(prof['weights'])} do not match dimensions")
    for rl in d["red_lines"]["rules"]:
        if rl["criterion"] not in seen:
            errs.append(f"red line {rl['id']} names unknown criterion {rl['criterion']}")
    marked = {c["id"] for dim in d["dimensions"] for c in dim["criteria"] if c.get("red_line")}
    listed = {rl["criterion"] for rl in d["red_lines"]["rules"]}
    if marked != listed:
        errs.append(f"red_line flags {sorted(marked)} differ from red_lines rules {sorted(listed)}")
    return errs


def render_json(d, digest):
    out = {"meta": {"source": "rqs-2030.yaml", "source_sha256": digest, "generated_by": "standard/build.py"}}
    out.update(d)
    return json.dumps(out, indent=1, ensure_ascii=False, default=str) + "\n"


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_md(d, digest):
    st = d["standard"]
    dims = d["dimensions"]
    crit = [c for dim in dims for c in dim["criteria"]]
    L = []
    w = L.append
    w(f"# {st['id']}: {st['title']}")
    w("")
    w(f"Version {st['version']} · {st['date']} · horizon {st['horizon']} · {len(dims)} dimensions, {len(crit)} criteria, "
      f"{len(d['opportunity_dimension']['criteria'])} opportunity criteria, {len(d['lenses']['gaps'])} gap lenses, "
      f"{len(d['lenses']['opportunities'])} opportunity lenses.")
    w("")
    w(f"> Generated by `standard/build.py` from `rqs-2030.yaml` (sha256 `{digest[:16]}`). Edit the YAML, not this file. "
      "Machine-readable copy: `rqs-2030.json`. Automated evidence and scoring: `tools/rqs`.")
    w("")
    w(f"**Status.** {st['status']}")
    w("")
    w(f"**Scope.** {st['scope']}")
    w("")
    w(f"**Audience.** {st['audience']}")
    w("")
    w("## Contents")
    w("")
    for i, t in enumerate(["How to run a review", "Principles", "Scale: levels and confidence", "Profiles and weights",
                           "Applicability flags", "Criteria", "Opportunity criteria", "Red lines", "Scoring and grades",
                           "Gap lenses", "Opportunity lenses", "Re-engineering actions", "Reviewer integrity",
                           "Report template", "Scoring worksheet", "References"], 1):
        w(f"{i}. [{t}](#{i}-{t.lower().replace(':', '').replace(' ', '-')})")
    w("")

    w("## 1. How to run a review")
    w("")
    w("| Step | Name | Do |")
    w("| --- | --- | --- |")
    for p in d["procedure"]:
        w(f"| {p['step']} | {md_escape(p['name'])} | {md_escape(p['do'])} |")
    w("")
    w("Quick start with the tooling: `tools/rqs/rqs.sh probe <repo> > evidence.json`, score the criteria in a review file "
      "(`rqs.sh template` prints one), then `rqs.sh score evidence.json review.json` and `rqs.sh report scorecard.json`.")
    w("")

    w("## 2. Principles")
    w("")
    for p in st["principles"]:
        w(f"- **{p['id']}.** {p['text']}")
    w("")

    w("## 3. Scale: levels and confidence")
    w("")
    w("| Level | Name | Meaning |")
    w("| --- | --- | --- |")
    for k, v in d["levels"].items():
        w(f"| {k} | {md_escape(v['name'])} | {md_escape(v['text'])} |")
    w("")
    w("| Confidence | Weight | Meaning |")
    w("| --- | --- | --- |")
    for k, v in d["confidence"].items():
        w(f"| {k} | {v['weight']} | {md_escape(v['text'])} |")
    w("")

    w("## 4. Profiles and weights")
    w("")
    w("Dimension weights per profile. A dimension's weight scales its share of the Quality Index.")
    w("")
    ids = [x["id"] for x in dims]
    w("| Profile | " + " | ".join(ids) + " |")
    w("| --- | " + " | ".join("---:" for _ in ids) + " |")
    for name, prof in d["profiles"].items():
        w(f"| {name} | " + " | ".join(str(prof["weights"][i]) for i in ids) + " |")
    w("")
    for name, prof in d["profiles"].items():
        w(f"- **{name}**: {prof['text']}")
    w("")

    w("## 5. Applicability flags")
    w("")
    w("Criteria with `applies if` are scored only when the flag is set; otherwise they are NA.")
    w("")
    for k, v in d["applicability_flags"].items():
        w(f"- `{k}`: {v}")
    w("")

    w("## 6. Criteria")
    w("")
    w("Each criterion states the question, why it matters, and anchors for a failing score (0-1), "
      "today's good practice (3) and the 2030-35 horizon (5). **Core** criteria weigh double; "
      "**red line** criteria cap the grade (section 8).")
    w("")
    for dim in dims:
        w(f"### {dim['id']}: {dim['name']}")
        w("")
        w(f"*{dim['intent']}* ISO/IEC 25010: {', '.join(dim['iso25010'])}.")
        w("")
        for c in dim["criteria"]:
            tags = []
            if c.get("core"):
                tags.append("core")
            if c.get("red_line"):
                tags.append("red line")
            if c.get("applies_if"):
                tags.append(f"applies if `{c['applies_if']}`")
            w(f"#### {c['id']} {c['title']}" + (f" ({', '.join(tags)})" if tags else ""))
            w("")
            w(f"**Question.** {c['question']}")
            w("")
            w(f"**Why.** {c['why']}")
            w("")
            w(f"- **Fails (0-1):** {c['fail']}")
            w(f"- **Meets (3):** {c['meets']}")
            w(f"- **Horizon (5):** {c['horizon']}")
            w(f"- **Evidence:** {', '.join(c['evidence'])}. **Probes:** {', '.join('`' + p + '`' for p in c['probes'])}. "
              f"**Refs:** {', '.join(c['refs'])}.")
            w("")

    od = d["opportunity_dimension"]
    w("## 7. Opportunity criteria")
    w("")
    w(f"{od['intent']}")
    w("")
    for c in od["criteria"]:
        w(f"- **{c['id']} {c['title']}.** {c['question']} Signals: {'; '.join(c['signals'])}.")
    w("")

    w("## 8. Red lines")
    w("")
    w(d["red_lines"]["effect"])
    w("")
    w("| ID | Criterion | Condition | Meaning |")
    w("| --- | --- | --- | --- |")
    for r in d["red_lines"]["rules"]:
        w(f"| {r['id']} | {r['criterion']} | {md_escape(r['condition'])} | {md_escape(r['text'])} |")
    w("")

    sc = d["scoring"]
    w("## 9. Scoring and grades")
    w("")
    for k in ("criterion", "dimension", "evidence_coverage", "quality_index", "horizon_index"):
        w(f"- **{k.replace('_', ' ').capitalize()}.** {sc[k]}")
    w("- **Grades.** " + ", ".join(f"{g} >= {v}" for g, v in sc["grade_bands"].items()) + " (Quality Index).")
    for g in sc["gates"]:
        w(f"- **Gate.** {g}")
    w(f"- **Opportunity priority.** {sc['opportunity_priority']}")
    w("")

    w("## 10. Gap lenses")
    w("")
    w("| ID | Lens | Ask | How |")
    w("| --- | --- | --- | --- |")
    for g in d["lenses"]["gaps"]:
        w(f"| {g['id']} | {md_escape(g['name'])} | {md_escape(g['ask'])} | {md_escape(g['how'])} |")
    w("")

    w("## 11. Opportunity lenses")
    w("")
    w("| ID | Lens | Heuristic | Where to look |")
    w("| --- | --- | --- | --- |")
    for g in d["lenses"]["opportunities"]:
        w(f"| {g['id']} | {md_escape(g['name'])} | {md_escape(g['heuristic'])} | {md_escape(g['query'])} |")
    w("")

    w("## 12. Re-engineering actions")
    w("")
    w("| Action | When |")
    w("| --- | --- |")
    for a in d["reengineering"]["actions"]:
        w(f"| {a['id']} | {md_escape(a['when'])} |")
    w("")
    w(d["reengineering"]["rule"])
    w("")

    w("## 13. Reviewer integrity")
    w("")
    for r in d["reviewer_integrity"]:
        w(f"- {r}")
    w("")

    w("## 14. Report template")
    w("")
    for i, r in enumerate(d["report_template"], 1):
        w(f"{i}. {r}")
    w("")

    w("## 15. Scoring worksheet")
    w("")
    w("Copy this table into a review. Level: 0-5, U or NA. Confidence: observed, derived or inferred. "
      "Evidence: file:line, command, or measurement.")
    w("")
    w("| Criterion | Title | Level | Confidence | Evidence |")
    w("| --- | --- | --- | --- | --- |")
    for c in crit:
        w(f"| {c['id']} | {md_escape(c['title'])} |  |  |  |")
    w("")

    w("## 16. References")
    w("")
    w("| ID | Reference | Note |")
    w("| --- | --- | --- |")
    for r in d["references"]:
        w(f"| {r['id']} | {md_escape(r['name'])} | {md_escape(r.get('note', ''))} |")
    w("")
    return "\n".join(L)


def main():
    raw = open(SRC, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    d = yaml.safe_load(raw)
    errs = validate(d)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        sys.exit(1)
    outs = {OUT_JSON: render_json(d, digest), OUT_MD: render_md(d, digest)}
    if "--check" in sys.argv[1:]:
        stale = [os.path.basename(p) for p, txt in outs.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != txt]
        if stale:
            print("stale, run standard/build.py: " + ", ".join(stale), file=sys.stderr)
            sys.exit(1)
        print("ok")
        return
    for p, txt in outs.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(txt)
    n = sum(len(x["criteria"]) for x in d["dimensions"])
    print(f"wrote rqs-2030.json and RQS-2030.md ({len(d['dimensions'])} dimensions, {n} criteria)")


if __name__ == "__main__":
    main()
