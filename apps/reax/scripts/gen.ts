// Generate everything that describes reax's operations from the one registry (src/ops/registry.ts):
//   docs/operations.md          one section per tool and operation (parity-check requires it)
//   docs/tools.json             the tool catalog an MCP client will see
//   docs/ledger/parity/*.jsonl  each parity row's reax.{tool,operation} mapping
//   node scripts/gen.ts [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { cmpKey, readDir } from "../src/ledger/io.ts";
import type { ParityRow } from "../src/ledger/schema.ts";
import { OPERATIONS } from "../src/ops/registry.ts";
import { type JsonSchema, type Operation, TOOLS } from "../src/ops/types.ts";

const REAX = join(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const stale: string[] = [];

function emit(rel: string, text: string): void {
  const p = join(REAX, rel);
  if (check) {
    if (!existsSync(p) || readFileSync(p, "utf8").replaceAll("\r\n", "\n") !== text) stale.push(rel);
  } else writeFileSync(p, text);
}

const type = (s: JsonSchema) =>
  s.enum
    ? s.enum.map((e) => JSON.stringify(e)).join(" \\| ")
    : s.type === "array"
      ? `${s.items?.type ?? "any"}[]`
      : (s.type ?? "any");

export function operationsMd(ops: readonly Operation[]): string {
  const out = [
    "# reax operations",
    "",
    "Generated by `scripts/gen.ts` from `src/ops/registry.ts`. Do not edit. Every example below runs as a",
    "test (`test/ops.test.ts`) against the fixture corpus.",
    "",
  ];
  for (const tool of TOOLS) {
    const mine = ops.filter((o) => o.tool === tool);
    if (!mine.length) continue;
    out.push(`## ${tool}`, "");
    for (const o of mine) {
      out.push(`### \`${o.name}\``, "", o.summary, "");
      out.push(
        `Effect: ${o.effect}. Cost: ${o.cost}. Output from the target is ${o.untrusted ? "untrusted (sent inside the untrusted-content envelope)" : "not target text"}. Platforms: ${o.platforms.join(", ")}.`,
        "",
      );
      out.push("| Argument | Type | Required | Default | Meaning |", "|---|---|---|---|---|");
      for (const [k, s] of Object.entries(o.input.properties ?? {})) {
        const bounds = [
          s.minimum !== undefined ? `≥ ${s.minimum}` : "",
          s.maximum !== undefined ? `≤ ${s.maximum}` : "",
          s.maxLength ? `≤ ${s.maxLength} chars` : "",
        ]
          .filter(Boolean)
          .join(", ");
        out.push(
          `| \`${k}\` | ${type(s)}${bounds ? ` (${bounds})` : ""} | ${o.input.required?.includes(k) ? "yes" : "no"} | ${s.default === undefined ? "" : `\`${JSON.stringify(s.default)}\``} | ${s.description ?? ""} |`,
        );
      }
      out.push("");
      for (const ex of o.examples)
        out.push(
          `Example: ${ex.title}.`,
          "",
          "```json",
          JSON.stringify({ operation: o.name, ...ex.args }),
          "```",
          "",
          "Result includes:",
          "",
          "```json",
          JSON.stringify(ex.expect),
          "```",
          "",
        );
      if (o.covers.length) out.push(`Ledger rows: ${o.covers.map((c) => `\`${c}\``).join(", ")}.`, "");
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}

export function toolCatalog(ops: readonly Operation[]) {
  return TOOLS.filter((t) => ops.some((o) => o.tool === t)).map((t) => {
    const mine = ops.filter((o) => o.tool === t);
    const readOnly = mine.every((o) => o.effect === "read");
    return {
      name: t,
      description: `${mine.map((o) => `${o.name}: ${o.summary}`).join(" ")} Pass operation and its arguments; see session describe for one operation's schema.`,
      operations: mine.map((o) => o.name),
      annotations: {
        readOnlyHint: readOnly,
        destructiveHint: false,
        idempotentHint: readOnly,
        openWorldHint: mine.some((o) => o.effect === "network"),
      },
    };
  });
}

/** Set every parity row's reax mapping from the registry; a row no operation covers maps to null. */
export function mapParity(rows: ParityRow[], ops: readonly Operation[]): ParityRow[] {
  const cover = new Map<string, Operation>();
  for (const o of ops)
    for (const k of o.covers) {
      if (cover.has(k)) throw new Error(`${k} is covered by both ${cover.get(k)!.name} and ${o.name}`);
      cover.set(k, o);
    }
  const known = new Set(rows.map((r) => r.key));
  for (const k of cover.keys())
    if (!known.has(k) && !k.startsWith("RX-"))
      throw new Error(`operation ${cover.get(k)!.name} covers ${k}, which is not a parity row`);
  return rows.map((r) => {
    const o = cover.get(r.key);
    return { ...r, reax: { tool: o?.tool ?? null, operation: o?.name ?? null, engine: r.reax.engine } };
  });
}

if (import.meta.main) {
  emit("docs/operations.md", operationsMd(OPERATIONS));
  emit("docs/tools.json", `${JSON.stringify(toolCatalog(OPERATIONS), null, 1)}\n`);
  const dir = join(REAX, "docs", "ledger", "parity");
  const byFile = new Map<string, ParityRow[]>();
  for (const { file, row } of readDir<ParityRow>(dir)) byFile.set(file, [...(byFile.get(file) ?? []), row]);
  const all = mapParity([...byFile.values()].flat(), OPERATIONS);
  const mapped = new Map(all.map((r) => [r.key, r]));
  for (const [file, rows] of byFile) {
    const next = rows.map((r) => mapped.get(r.key)!).sort((a, b) => cmpKey(a.key, b.key));
    const text = `${next.map((r) => JSON.stringify(r)).join("\n")}\n`;
    emit(`docs/ledger/parity/${file}`, text);
  }
  if (check) {
    for (const s of stale) console.error(`stale: ${s} (run node scripts/gen.ts)`);
    console.log(stale.length ? `${stale.length} generated files are stale` : "generated files are current");
    process.exit(stale.length ? 1 : 0);
  }
  console.log(`${OPERATIONS.length} operations -> docs/operations.md, docs/tools.json, parity mappings`);
}
